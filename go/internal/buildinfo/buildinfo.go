// Package buildinfo — встраиваемая в бинарники информация о сборке.
package buildinfo

import (
	"fmt"
	"os"
)

// Copyright — уведомление об авторстве. Намеренно var + используется в
// init() (blank-импорт из cmd-программ), чтобы линковщик сохранил строку
// в rodata бинарника: комментарии Go в бинарник не попадают, а неиспользуемые
// глобальные строки выбрасываются оптимизатором.
var Copyright = "Copyright (c) 2026 Di1r1 — https://github.com/Di1r1/entware-manager"

// init выводит копирайт, если задан EWM_CREDITS=1 (скрытая диагностика:
// запуск любого бинарника с этой переменной показывает автора). Обычный
// запуск на это условие не попадает, но ссылка на Copyright в коде
// гарантирует, что строка остаётся в бинарнике.
func init() {
	if os.Getenv("EWM_CREDITS") == "1" {
		fmt.Println(Copyright)
		os.Exit(0)
	}
}
